def convert_file(filepath):
    """轉換單個文件"""
    try:
        # 讀取文件
        content = filepath.read_text(encoding='utf-8')
        original_content = content
        
        # 逐個替換
        for simplified, traditional in CONVERSION_MAP.items():
            content = content.replace(simplified, traditional)
        
        # 如果有變化則寫回
        if content != original_content:
            filepath.write_text(content, encoding='utf-8')
            return True
        return False
    except Exception as e:
        print(f"錯誤處理 {filepath.name}: {e}")
        return False

def main():
    """主程序"""
    intro_dir = Path('introduction')
    
    if not intro_dir.exists():
        print(f"錯誤：找不到 'introduction' 文件夾")
        return
    
    # 取得所有md文件
    md_files = sorted(intro_dir.glob('*.md'))
    
    if not md_files:
        print("錯誤：未找到任何md文件")
        return
    
    print(f"找到 {len(md_files)} 個md文件，開始轉換...")
    print("-" * 50)
    
    converted_count = 0
    
    for md_file in md_files:
        if convert_file(md_file):
            print(f"✓ {md_file.name:30} - 已轉換為繁體中文")
            converted_count += 1
        else:
            print(f"  {md_file.name:30} - 無需轉換或已是繁體")
    
    print("-" * 50)
    print(f"\n完成！共轉換了 {converted_count} 個文件")

if __name__ == '__main__':
    main()
